const CACHE = "prva-smena-v1";
const CORE = ["/", "/index.html", "/manifest.json", "/fonts/Roboto-Regular.ttf", "/fonts/Roboto-Bold.ttf", "/img/hero.jpg", "/img/icon-192.png"];

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(CORE)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});
self.addEventListener("fetch", (e) => {
  const req = e.request;
  const url = new URL(req.url);
  if (req.method !== "GET" || url.pathname.startsWith("/api") || url.pathname.includes("hot-update") || url.pathname.startsWith("/ws") || url.pathname.includes("sockjs")) return;
  if (!url.protocol.startsWith("http")) return;
  e.respondWith(
    fetch(req)
      .then((res) => {
        if (res && (res.ok || res.type === "opaque")) {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(req, copy));
        }
        return res;
      })
      .catch(() => caches.match(req).then((r) => r || (req.mode === "navigate" ? caches.match("/index.html") : undefined))),
  );
});
